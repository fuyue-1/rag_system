def insert_data():
    # 先连到实例（不指定库），建库 + 建表，再切库灌数据 —— 全新环境也能一条命令跑通
    cfg = dict(DB_CONFIG)
    db_name = cfg.pop('database')
    conn = pymysql.connect(**cfg)
    cursor = conn.cursor()
    cursor.execute(
        f"CREATE DATABASE IF NOT EXISTS `{db_name}` DEFAULT CHARACTER SET utf8mb4")
    cursor.execute(f"USE `{db_name}`")
    cursor.execute(SCHEMA_NECTAR)
    cursor.execute(SCHEMA_KNOWLEDGE)
    conn.commit()
    print(f"[建库建表] 数据库 {db_name} 就绪（nectar_sources / bee_knowledge）")

    # 清空旧数据（脚本可重复执行；注意会覆盖这两张表已有内容）
    cursor.execute("TRUNCATE TABLE nectar_sources")
    cursor.execute("TRUNCATE TABLE bee_knowledge")

    # 插入蜜源数据
    sql_nectar = """INSERT INTO nectar_sources
        (plant_name, plant_category, is_primary, province, city, location_name,
         latitude, longitude, planting_area, annual_avg_temp, annual_precipitation,
         sunshine_hours, climate_type, flowering_start, flowering_end,
         best_honey_start, best_honey_end, honey_yield, nectar_sugar_content,
         pollen_quality, description)
        VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)"""

    for item in NECTAR_SOURCES:
        cursor.execute(sql_nectar, item)

    # 插入知识库数据
    sql_knowledge = """INSERT INTO bee_knowledge
        (title, category, content, tags)
        VALUES (%s, %s, %s, %s)"""

    for item in KNOWLEDGE_ENTRIES:
        cursor.execute(sql_knowledge, item)

    # 追加 expand_knowledge.py 里的进阶知识（45 篇），让知识库达到与线上一致的 55 篇。
    # 同文件导入失败也不影响主流程，最坏情况是只有基础 10 篇。
    titles = {item[0] for item in KNOWLEDGE_ENTRIES}
    try:
        from expand_knowledge import ARTICLES as _EXTRA_ARTICLES
    except Exception as e:                       # noqa: BLE001
        print(f"[提示] 未能加载 expand_knowledge.ARTICLES（{e}），仅导入基础 10 篇知识")
        _EXTRA_ARTICLES = []
    extra_added = 0
    for item in _EXTRA_ARTICLES:
        if item[0] in titles:                     # 按标题去重，脚本可重复执行
            continue
        cursor.execute(sql_knowledge, item)
        titles.add(item[0])
        extra_added += 1
    print(f"[知识库] 基础 10 篇 + 进阶 {extra_added} 篇")

    conn.commit()

    # 验证
    cursor.execute("SELECT COUNT(*) FROM nectar_sources")
    nectar_count = cursor.fetchone()[0]
    cursor.execute("SELECT COUNT(DISTINCT plant_name) FROM nectar_sources")
    plant_count = cursor.fetchone()[0]
    cursor.execute("SELECT COUNT(DISTINCT province) FROM nectar_sources")
    province_count = cursor.fetchone()[0]
    cursor.execute("SELECT COUNT(*) FROM bee_knowledge")
    knowledge_count = cursor.fetchone()[0]

    cursor.close()
    conn.close()

    print(f"蜜源数据导入完成:")
    print(f"  蜜源记录数: {nectar_count}")
    print(f"  蜜源植物种数: {plant_count}")
    print(f"  覆盖省份: {province_count}")
    print(f"  知识库条目: {knowledge_count}")


if __name__ == "__main__":
    insert_data()
