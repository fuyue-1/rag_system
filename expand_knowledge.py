def main():
    conn = pymysql.connect(
        host=os.environ.get('MYSQL_HOST', '127.0.0.1'),
        port=int(os.environ.get('MYSQL_PORT', 3306)),
        user=os.environ.get('MYSQL_USER', 'root'),
        password=os.environ.get('MYSQL_PASSWORD') or '123456',
        database=os.environ.get('MYSQL_DATABASE', 'bee_rag'),
        charset='utf8mb4')
    cur = conn.cursor()
    cur.execute('SELECT title FROM bee_knowledge')
    existing = {r[0] for r in cur.fetchall()}
    added = 0
    for title, category, content, tags in ARTICLES:
        if title in existing:
            continue
        cur.execute(
            'INSERT INTO bee_knowledge (title, category, content, tags) VALUES (%s,%s,%s,%s)',
            (title, category, content, tags))
        added += 1
    conn.commit()
    cur.execute('SELECT COUNT(*) FROM bee_knowledge')
    print(f'新增 {added} 篇，当前共 {cur.fetchone()[0]} 篇')
    conn.close()

if __name__ == '__main__':
    main()
